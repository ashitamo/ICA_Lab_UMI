import numpy as np
from scipy.signal import butter, filtfilt
import copy # 用來深拷貝資料

def smooth_trajectory_with_lowpass(
    trajectory: list, 
    duration: float, 
    cutoff: float = 2.0, 
    order: int = 4
) -> list:
    """
    使用巴特沃斯低通濾波器 (Butterworth Low-Pass Filter) 平滑軌跡。
    """
    # 1. 基礎檢查
    if not trajectory or duration <= 0:
        print("警告 (LowPass): 軌跡為空或持續時間無效，不進行平滑。")
        return trajectory
    
    data = np.array(trajectory)
    n_samples, n_dims = data.shape
    
    # 2. 計算取樣頻率
    fs = n_samples / duration
    
    # 3. 檢查軌跡長度
    if n_samples <= 3 * order:
        print(f"警告 (LowPass): 軌跡點數 ({n_samples}) 過少，回傳原始軌跡。")
        return trajectory

    # 4. 設計濾波器
    nyquist = 0.5 * fs
    
    if cutoff >= nyquist:
        adjusted_cutoff = nyquist - 0.1
        if adjusted_cutoff <= 0: adjusted_cutoff = 0.1
        print(f"警告 (LowPass): 截止頻率 {cutoff} Hz 過高，自動調整為 {adjusted_cutoff:.2f} Hz。")
        cutoff = adjusted_cutoff
        
    normal_cutoff = cutoff / nyquist
    
    try:
        b, a = butter(order, normal_cutoff, btype='low', analog=False)
        # 5. 執行零相位濾波
        smoothed_data = filtfilt(b, a, data, axis=0)
        
    except Exception as e:
        print(f"錯誤 (LowPass): 濾波過程失敗 ({e})。回傳原始軌跡。")
        return trajectory

    # 6. 四元數重新正規化 (重要！)
    if n_dims >= 7:
        # 假設 index 3:7 是 [qx, qy, qz, qw]
        quaternions = smoothed_data[:, 3:7]
        norms = np.linalg.norm(quaternions, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        smoothed_data[:, 3:7] = quaternions / norms

    return smoothed_data.tolist()


def apply_velocity_filter(traj_list, cutoff_freq: float = 1.0, order: int = 4):
    """
    (已修正) 簡單版濾波，僅針對前三維 XYZ 處理。
    注意：此函式不會正規化四元數，建議使用 smooth_trajectory_with_lowpass。
    """
    if len(traj_list) < 10:
        return traj_list

    # 深拷貝以避免修改原始資料
    xyz_list = [row[:3] for row in traj_list] 
    
    # 假設採樣率固定為 30 (較不彈性)
    sampling_freq = 30
    nyquist_freq = sampling_freq / 2.0
    normalized_cutoff = cutoff_freq / nyquist_freq

    if normalized_cutoff >= 1.0:
        print("Warning: Cutoff too high.")
        return traj_list

    b, a = butter(order, normalized_cutoff, btype='low', analog=False)
    xyz_filtered = filtfilt(b, a, xyz_list, axis=0)

    # 回寫數據 (產生一個新列表回傳，不修改輸入)
    new_traj = copy.deepcopy(traj_list)
    for i in range(len(new_traj)):
        new_traj[i][0] = float(xyz_filtered[i][0])
        new_traj[i][1] = float(xyz_filtered[i][1])
        new_traj[i][2] = float(xyz_filtered[i][2])

    print(f"Applied low-pass filter (cutoff={cutoff_freq} Hz)")
    return new_traj


